// `primo-alpine tokens import`: turns an inspector snapshot into committed, editor-friendly files.
'use strict';

const fs = require('fs');
const path = require('path');
const { loadConfig } = require('./config');

// ---------------------------------------------------------------------------
// Tokens: primo-alpine tokens import <snapshot.json> --env <env>
// ---------------------------------------------------------------------------

function importTokens(snapshotPath, env, { root } = {}) {
  const ctx = loadConfig(root);
  const projectRoot = ctx.root;
  if (!snapshotPath || !fs.existsSync(snapshotPath)) throw new Error(`Snapshot not found: ${snapshotPath}`);
  if (!env) throw new Error('--env is required');
  const snapshot = JSON.parse(fs.readFileSync(snapshotPath, 'utf8'));
  if (snapshot.format !== 'primo-alpine-tokens@1' || !Array.isArray(snapshot.tokens)) {
    throw new Error('Not a primo-alpine token snapshot (export it with the ?ndeTokens=1 inspector)');
  }
  const outDir = path.join(ctx.abs(ctx.config.tokensDir), env);
  fs.mkdirSync(outDir, { recursive: true });

  // 1. The snapshot itself, committed: a diff after a Primo upgrade names added/removed tokens.
  const previousPath = path.join(outDir, `tokens.${env}.json`);
  const previous = fs.existsSync(previousPath) ? JSON.parse(fs.readFileSync(previousPath, 'utf8')) : null;
  fs.writeFileSync(previousPath, JSON.stringify(snapshot, null, 2) + '\n');

  // 2. SCSS variables pointing at the custom properties (autocomplete in style.scss via @use).
  const scss = [
    `// AUTO-GENERATED by \`primo-alpine tokens import\` for ${env} — DO NOT EDIT.`,
    `// Snapshot: ${snapshot.url} (${snapshot.collectedAt})`,
    `// Usage in an island's style.scss: @use '<relative path to this folder>/tokens' as t;`,
    '//   color: t.$mat-sys-primary;',
    '',
    ...snapshot.tokens.map((t) => `$${t.name.slice(2)}: var(${t.name}); // ${t.values.default}`),
    '',
  ].join('\n');
  fs.writeFileSync(path.join(outDir, '_tokens.scss'), scss);

  // 3. A CSS file declaring every token, for editor var(--…) completion. VS Code's built-in CSS
  //    service only completes variables declared in the current file, so this file is read by the
  //    "CSS Variable Autocomplete" extension (see .vscode/settings.json).
  const css = [
    `/* AUTO-GENERATED token declarations for ${env}, for editor autocomplete only. Not shipped. */`,
    ':root {',
    ...snapshot.tokens.map((t) => `  ${t.name}: ${t.values.default || 'initial'};`),
    '}',
    '',
  ].join('\n');
  fs.writeFileSync(path.join(outDir, `tokens.${env}.css`), css);

  // 4. Grouped table for the authoring docs.
  const groups = new Map();
  for (const t of snapshot.tokens) {
    if (!groups.has(t.group)) groups.set(t.group, []);
    groups.get(t.group).push(t);
  }
  const themes = (snapshot.themes ?? ['default']).filter((t) => t !== 'default');
  const md = [
    `# Design tokens: ${env}`,
    '',
    `Generated by \`primo-alpine tokens import\` from a snapshot of ${snapshot.url} taken ${snapshot.collectedAt}.`,
    `${snapshot.tokens.length} tokens. Use them as \`var(--name)\` in an island's \`style.scss\`.`,
    '',
  ];
  for (const [group, tokens] of [...groups.entries()].sort()) {
    md.push(`## ${group}`, '', `| Token | Kind | Value |${themes.map((t) => ` ${t} |`).join('')}`, `|---|---|---|${themes.map(() => '---|').join('')}`);
    for (const t of tokens) {
      const cell = (v) => (v ? `\`${v.replace(/\|/g, '\\|')}\`` : '');
      md.push(`| \`${t.name}\` | ${t.kind} | ${cell(t.values.default)} |${themes.map((th) => ` ${cell(t.values[th])} |`).join('')}`);
    }
    md.push('');
  }
  fs.writeFileSync(path.join(outDir, 'TOKENS.md'), md.join('\n'));

  // 5. Point the editor at the CSS declarations of every environment.
  updateVscodeSettings(projectRoot, path.relative(projectRoot, ctx.abs(ctx.config.tokensDir)));

  console.log(`✓ Imported ${snapshot.tokens.length} tokens for ${env} into ${path.relative(projectRoot, outDir)}`);
  if (previous) {
    const before = new Set(previous.tokens.map((t) => t.name));
    const after = new Set(snapshot.tokens.map((t) => t.name));
    const added = [...after].filter((n) => !before.has(n));
    const removed = [...before].filter((n) => !after.has(n));
    console.log(`  ${added.length} added, ${removed.length} removed since the previous snapshot`);
    removed.slice(0, 20).forEach((n) => console.log(`  - ${n}`));
    added.slice(0, 20).forEach((n) => console.log(`  + ${n}`));
  }
}

function updateVscodeSettings(projectRoot, tokensDir) {
  const settingsPath = path.join(projectRoot, '.vscode', 'settings.json');
  let settings = {};
  if (fs.existsSync(settingsPath)) {
    try {
      settings = JSON.parse(fs.readFileSync(settingsPath, 'utf8'));
    } catch {
      console.warn('  .vscode/settings.json is not plain JSON; add "cssVariables.lookupFiles" yourself.');
      return;
    }
  }
  const glob = `${tokensDir.split(path.sep).join('/')}/**/*.css`;
  const lookup = new Set(settings['cssVariables.lookupFiles'] ?? ['**/*.css', '**/*.scss']);
  lookup.add(glob);
  settings['cssVariables.lookupFiles'] = [...lookup];
  fs.mkdirSync(path.dirname(settingsPath), { recursive: true });
  fs.writeFileSync(settingsPath, JSON.stringify(settings, null, 2) + '\n');

  const extensionsPath = path.join(projectRoot, '.vscode', 'extensions.json');
  let extensions = { recommendations: [] };
  if (fs.existsSync(extensionsPath)) {
    try {
      extensions = JSON.parse(fs.readFileSync(extensionsPath, 'utf8'));
    } catch {
      return;
    }
  }
  const recs = new Set(extensions.recommendations ?? []);
  recs.add('vunguyentuan.vscode-css-variables');
  extensions.recommendations = [...recs];
  fs.writeFileSync(extensionsPath, JSON.stringify(extensions, null, 2) + '\n');
}

module.exports = { importTokens };
